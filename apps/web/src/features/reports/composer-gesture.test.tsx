import {render,fireEvent,cleanup} from '@testing-library/react';
import {afterEach,it,expect,vi} from 'vitest';
import {ComposerCanvas} from './ComposerCanvas';
import {readFileSync} from 'node:fs';
const styles=readFileSync('src/features/reports/composer.css','utf8');
import type {Definition} from './composer-state';

afterEach(()=>{cleanup();vi.restoreAllMocks();vi.unstubAllGlobals();});
it('selects on click without grid feedback or layout commit, but reveals the grid on movement',()=>{
 vi.stubGlobal('ResizeObserver',class{observe(){} disconnect(){}});
 vi.spyOn(HTMLElement.prototype,'offsetParent','get').mockImplementation(function(this:HTMLElement){return this.parentElement;});
 vi.spyOn(HTMLElement.prototype,'clientWidth','get').mockReturnValue(960);
 const block={block_id:'block',section_id:'section',order:0,block_type:'text' as const,presentation:{title:'Text'},placement:{column:0,row:0,span:6,row_span:2}};
 const neighbor={...block,block_id:'neighbor',order:1,presentation:{title:'Neighbor'},placement:{column:8,row:4,span:6,row_span:2}};
 const ref={id:crypto.randomUUID(),content_hash:'a'.repeat(64)};
 const d:Definition={document_id:crypto.randomUUID(),creator_principal_id:crypto.randomUUID(),title:'Report',profile:'workbook_report',brand_profile:ref,company_pack:ref,default_page_id:'page',chapters:[],definitions:[],grid_columns:24,pages:[{page_id:'page',title:'Page',order:0,layout:'dashboard_grid'}],sections:[{section_id:'section',page_id:'page',title:'Section',order:0}],blocks:[block,neighbor]};
 const commit=vi.fn(),select=vi.fn();
 const {container,getByText}=render(<div className="composer-prototype"><style>{styles}</style><ComposerCanvas definition={d} section="section" blocks={d.blocks} selected={null} select={select} readOnly={false} busy={false} locale="en" commit={commit} copy={()=>{}} remove={()=>{}} render={b=> <p>{b.block_id===block.block_id?'Content':'Neighbor'}</p>}/></div>);
 const canvas=container.querySelector('.composer-canvas')!,content=getByText('Content');
 fireEvent.mouseDown(content,{button:0,clientX:30,clientY:30});
 expect(canvas.classList.contains('is-dragging')).toBe(false);
 fireEvent.mouseUp(document,{button:0,clientX:30,clientY:30});fireEvent.click(content);
 expect(select).toHaveBeenCalledWith('block');expect(commit).not.toHaveBeenCalled();expect(document.body.classList.contains('composer-pointer-active')).toBe(false);
 fireEvent.mouseDown(content,{button:0,clientX:30,clientY:30});
 fireEvent.mouseMove(document,{buttons:1,clientX:100,clientY:100});
 expect(canvas.classList.contains('is-dragging')).toBe(true);
 const active=container.querySelector('.react-draggable-dragging,.resizing')!;
 expect(getComputedStyle(active).zIndex).toBe('20');
 expect(getComputedStyle(container.querySelector('.react-grid-placeholder')!).display).toBe('none');
 fireEvent.mouseUp(document,{button:0,clientX:100,clientY:100});
 expect(canvas.classList.contains('is-dragging')).toBe(false);
 const resize=container.querySelector('.react-resizable-handle')!;
 fireEvent.mouseDown(resize,{button:0,clientX:240,clientY:80});
 expect(document.body.classList.contains('composer-pointer-active')).toBe(true);
 expect(document.dispatchEvent(new Event('selectstart',{cancelable:true}))).toBe(false);
 expect(canvas.classList.contains('is-dragging')).toBe(false);
 fireEvent.mouseMove(document,{buttons:1,clientX:280,clientY:140});
 expect(canvas.classList.contains('is-dragging')).toBe(true);
 expect(getComputedStyle(container.querySelector('.resizing')!).zIndex).toBe('20');
 expect(getComputedStyle(container.querySelector('.react-grid-placeholder')!).display).toBe('none');
 expect(getComputedStyle(container.querySelector('.composer-block-tools')!).opacity).toBe('0');
 fireEvent.mouseUp(document,{button:0,clientX:280,clientY:140});
 expect(document.body.classList.contains('composer-pointer-active')).toBe(false);
 expect(document.dispatchEvent(new Event('selectstart',{cancelable:true}))).toBe(true);
 expect(canvas.classList.contains('is-dragging')).toBe(false);
 fireEvent.mouseDown(resize,{button:0,clientX:280,clientY:140});
 expect(document.body.classList.contains('composer-pointer-active')).toBe(true);
 fireEvent.blur(window);
 expect(document.body.classList.contains('composer-pointer-active')).toBe(false);
 fireEvent.mouseUp(document,{button:0,clientX:280,clientY:140});

 fireEvent.mouseDown(resize,{button:0,clientX:280,clientY:140});
 fireEvent.mouseMove(document,{buttons:1,clientX:800,clientY:500});
 const resizing=container.querySelector('.resizing')!;
 const other=container.querySelector('[data-block-id="neighbor"]')!;
 expect(getComputedStyle(resizing).zIndex).toBe('20');
 expect(getComputedStyle(resizing).opacity).toBe('1');
 expect(getComputedStyle(other).zIndex).toBe('0');
 expect(getComputedStyle(container.querySelector('.react-grid-placeholder')!).display).toBe('none');
 fireEvent.mouseUp(document,{button:0,clientX:800,clientY:500});
 expect(commit).toHaveBeenCalled();
 const committed=commit.mock.calls.at(-1)![0] as Definition;
 expect(committed.blocks.find(b=>b.block_id==='neighbor')!.placement).toEqual(neighbor.placement);
 expect(canvas.classList.contains('is-dragging')).toBe(false);
 expect(document.body.classList.contains('composer-pointer-active')).toBe(false);

});
